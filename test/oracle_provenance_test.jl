using Test

const _ORACLE_DIR = @__DIR__

# The oracle DATA files: flat pinned-literal lists, named `_oracle*.jl`.
# (`_test.jl` files carry test LOGIC, not pinned data, and are excluded —
# their provenance lives in the data files they `include`.)
_oracle_data_files() =
    sort(filter(f -> startswith(f, "_oracle") && endswith(f, ".jl"),
                readdir(_ORACLE_DIR)))

# The LEADING comment header: the contiguous run of `#`-comment / blank
# lines from the top of the file, stopping at the first line of code.
# Blank lines INSIDE the banner are kept (headers use them as spacers);
# the run ends at the first non-blank, non-comment line.
function _leading_header(path::AbstractString)
    io = IOBuffer()
    for line in eachline(path)
        s = lstrip(line)
        if startswith(s, "#") || isempty(strip(line))
            println(io, line)
        else
            break
        end
    end
    return String(take!(io))
end

# A SOURCE marker names the ground-truth CLASS the literals were derived
# from.  Matched case-insensitively; the alternatives are exactly the
# ground-truth vocabulary the corpus already uses (surveyed across all 25
# files).  `\b` on the multi-word forms tolerates "closed form" / "closed-
# form" / "closedform" spellings.
const _SOURCE_MARKERS = Regex(
    "(?i)(" * join([
        "closed[ -]?form",
        "exact[ -]?(rational|algebraic|integer)",
        "mpmath",
        "mathematica|wolfram(script)?|ndsolve|asymptoticdsolve",
        "sympy",
        "scipy",
        "taylorintegration",
        "dmsuite",
        "padeapprox\\.m",
        "calgo|fortran",
        "dlmf",
        "binomial",
        "provenance",
    ], "|") * ")")

# A REGENERATION marker names HOW to re-derive: a capture-script path or an
# explicit regenerate/auto-generated phrase.  This is what makes the golden
# AUDITABLE — a reviewer can re-run it and diff (the krgy.9 discipline).
const _REGEN_MARKERS = Regex(
    "(?i)(" * join([
        "capture\\.(py|wl|m|jl)",
        "verify\\.jl",
        "regeneration oracle",
        "generated by",
        "auto-generated by",
        "regenerate",
        "re-?run",
        "provenance",
    ], "|") * ")")

# Header substance floor: a marker buried in a one-line stub is not a
# provenance block.  Real headers in this corpus run dozens of lines; we
# require a modest minimum so a token alone can't satisfy the contract.
const _MIN_HEADER_LINES = 3
const _MIN_HEADER_CHARS = 80

@testset "Oracle provenance contract (bead padetaylor-krgy.9)" begin
    files = _oracle_data_files()

    # The corpus is large and growing; a regression that DELETES every
    # oracle file would vacuously pass an empty loop.  Pin the floor.
    @test length(files) ≥ 20

    @testset "provenance header: $f" for f in files
        header = _leading_header(joinpath(_ORACLE_DIR, f))

        # NON-TRIVIAL header — substance, not a bare token (Rule 5).
        nlines = count(==('\n'), header)
        @test nlines ≥ _MIN_HEADER_LINES
        @test length(strip(header)) ≥ _MIN_HEADER_CHARS

        # SOURCE present + non-empty.
        src = match(_SOURCE_MARKERS, header)
        @test src !== nothing
        @test src === nothing || !isempty(src.match)

        # REGENERATION / derivation reference present + non-empty.
        regen = match(_REGEN_MARKERS, header)
        @test regen !== nothing
        @test regen === nothing || !isempty(regen.match)
    end
end

