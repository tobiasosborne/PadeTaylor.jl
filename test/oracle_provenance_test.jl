# ## Why this file exists — provenance as an ENFORCED contract, not lore
#
# The corpus is anchored by ~25 `test/_oracle_*.jl` files: flat lists of
# pinned literals (closed-form values, mpmath/Mathematica/sympy captures,
# exact rationals) that the `_test.jl` bodies assert against.  A pinned
# literal is only trustworthy if a future reader can answer two questions
# WITHOUT archaeology:
#
#   1. SOURCE      — where did this number come from?  (closed form? an
#                    mpmath dps=50 capture?  an exact rational?  a FORTRAN
#                    reference impl?)  Rule 5: an oracle whose source is
#                    unknown cannot certify anything.
#   2. REGENERATION — how do I re-derive or re-capture it, so the diff is
#                    auditable when the oracle changes?  (which capture
#                    script / verify.jl / closed-form one-liner?)  This is
#                    the krgy.9 snapshot-approval discipline: regenerate →
#                    review `git diff` → approve-commit.
#
# The well-formed oracle files ALREADY answer both — most carry a rich
# `REGENERATION ORACLE:` / `Generated by:` / `PROVENANCE` header naming a
# `external/probes/.../capture.{py,wl,m,jl}` script and a ground-truth
# class.  This test promotes that *de facto* convention into an *enforced*
# contract (Rule 9: a doc nobody checks rots; a test that goes RED does
# not).  It is the executable companion to the runbook
# `docs/test_corpus/04_snapshot_approval_workflow.md`.
#
# ## The contract this test asserts (the convention, verbatim)
#
# For every `test/_oracle*.jl` data file, its LEADING COMMENT HEADER
# (the contiguous `#`-comment block at the top, before the first code
# line) must contain BOTH, non-empty:
#
#   * a SOURCE marker — naming the ground-truth class.  Any of:
#       closed-form · exact rational/algebraic · mpmath · Mathematica /
#       wolfram / NDSolve · sympy · scipy · TaylorIntegration · DMSUITE ·
#       padeapprox.m · Calgo / FORTRAN · DLMF · binomial · PROVENANCE.
#   * a REGENERATION marker — naming how to re-derive.  Any of:
#       a capture-script path (`capture.py|.wl|.m|.jl`, `verify.jl`) OR an
#       explicit regen phrase (`REGENERATION ORACLE`, `Generated by`,
#       `auto-generated by`, `regenerate`, `re-run`/`Re-run`, `PROVENANCE`).
#
# This is a REAL invariant (Rule 5): the markers must be PRESENT and the
# header NON-TRIVIAL (≥ 3 comment lines, ≥ 80 chars of prose) — not
# "the file parsed".  Blank a marker out of any header and this test
# goes RED (mutation-proof in the footer).
